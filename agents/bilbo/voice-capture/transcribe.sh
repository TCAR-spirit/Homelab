#!/usr/bin/env bash
#
# Bilbo transcription pipeline — turn a session recording directory of
# per-speaker WAV files into ONE merged, timestamped, speaker-tagged transcript.
#
# Pipeline (local, on the debian VM — audio never leaves the box):
#   per-speaker WAV  --ffmpeg-->  16kHz mono WAV  --whisper.cpp-->  per-speaker
#   timestamped segments  -->  merged & sorted by time  -->  transcript.txt
#
# The in-character Bilbo agent then reads transcript.txt and writes the recap
# DRAFT into the vault (40 - Campaign/41 - Session Notes/). This script does NOT
# touch the vault.
#
# Usage:  transcribe.sh <session_dir>
#   e.g.  transcribe.sh ~/bilbo-voice/sessions/session_2026-11-21_19-30-00
#
# Model: small.en by default (accuracy over speed for a faithful chronicle; see
# ../DECISION-DOC.md D4). Override with BILBO_WHISPER_MODEL.
set -euo pipefail

SESSION_DIR="${1:?usage: transcribe.sh <session_dir>}"
WHISPER_DIR="${BILBO_WHISPER_DIR:-$HOME/bilbo-voice/tools/whisper.cpp}"
MODEL="${BILBO_WHISPER_MODEL:-$WHISPER_DIR/models/ggml-small.en.bin}"
WHISPER_BIN="$WHISPER_DIR/build/bin/whisper-cli"
THREADS="${BILBO_WHISPER_THREADS:-4}"

[ -d "$SESSION_DIR" ] || { echo "no such session dir: $SESSION_DIR" >&2; exit 1; }
[ -x "$WHISPER_BIN" ]  || { echo "whisper-cli not found/executable at $WHISPER_BIN" >&2; exit 1; }
[ -f "$MODEL" ]        || { echo "model not found: $MODEL" >&2; exit 1; }

WORK="$SESSION_DIR/_work"
mkdir -p "$WORK"
MERGED="$SESSION_DIR/_segments.tsv"   # timestamp <tab> speaker <tab> text
: > "$MERGED"

echo "Transcribing session: $SESSION_DIR"
echo "Model: $MODEL  (threads: $THREADS)"

shopt -s nullglob
wavs=("$SESSION_DIR"/*.wav)
if [ ${#wavs[@]} -eq 0 ]; then
  echo "no .wav files in $SESSION_DIR" >&2; exit 1
fi

for wav in "${wavs[@]}"; do
  base="$(basename "$wav" .wav)"
  # Speaker name is the part after the "<userid>__" prefix (see receiver naming).
  speaker="${base#*__}"
  [ "$speaker" = "$base" ] && speaker="$base"   # no prefix -> use whole name
  echo "  -> speaker: $speaker"

  # 1) normalize to 16kHz mono WAV (what whisper wants)
  norm="$WORK/${base}.16k.wav"
  ffmpeg -nostdin -y -loglevel error -i "$wav" -ar 16000 -ac 1 "$norm"

  # 2) whisper.cpp -> CSV with timestamps (-ocsv writes <base>.csv next to -of)
  of="$WORK/${base}"
  "$WHISPER_BIN" -m "$MODEL" -f "$norm" -t "$THREADS" -ocsv -of "$of" >/dev/null 2>&1

  # 3) CSV rows: start,end,text  -> append  start_ms <tab> speaker <tab> text
  csv="$of.csv"
  if [ -f "$csv" ]; then
    # skip header; whisper csv is: start,end,"text"
    tail -n +2 "$csv" | while IFS=, read -r start end rest; do
      # rest is the quoted text (may contain commas); strip surrounding quotes
      text="$(echo "$rest" | sed -e 's/^"//' -e 's/"$//' -e 's/""/"/g')"
      [ -z "${text// /}" ] && continue
      printf '%012d\t%s\t%s\n' "${start:-0}" "$speaker" "$text" >> "$MERGED"
    done
  fi
done

# 4) sort all speakers' segments by timestamp, format as a readable transcript
TRANSCRIPT="$SESSION_DIR/transcript.txt"
{
  echo "# Session transcript (auto-generated by Bilbo's local pipeline)"
  echo "# Source: $SESSION_DIR"
  echo "# Model: $(basename "$MODEL")   Generated: $(date -Iseconds)"
  echo "# Speaker-tagged, time-ordered. This is the GROUND TRUTH for the recap."
  echo "# Bilbo narrates ONLY what appears here; silence here = silence in the recap."
  echo
  sort -n "$MERGED" | while IFS=$'\t' read -r ms speaker text; do
    # ms is whisper start time in milliseconds -> mm:ss
    total_s=$(( ms / 1000 ))
    printf '[%02d:%02d] %s: %s\n' $(( total_s / 60 )) $(( total_s % 60 )) "$speaker" "$text"
  done
} > "$TRANSCRIPT"

echo
echo "✓ transcript written: $TRANSCRIPT"
echo "  ($(grep -c '^\[' "$TRANSCRIPT" 2>/dev/null || echo 0) lines of dialogue)"
echo
echo "Next: hand $TRANSCRIPT to the in-character Bilbo agent, e.g.:"
echo "  bilbo -z \"Write a session recap draft from this transcript: \$(cat '$TRANSCRIPT')\""
